// ?autoplay: vào thẳng phòng test (scripts/test-events.js); ở mode này không có cú click nào để xin khoá chuột.
const autoplay = new URLSearchParams(location.search).has('autoplay');

initMenu((name, look, intent) => {
  state.joined = true;
  setLocalLook(look);
  Sfx.init();
  preloadNukeSounds();
  connect(name, look, intent);
  if (!autoplay) canvas.requestPointerLock(); // ?autoplay không có cú click nào để xin khoá chuột; bấm vào sân để khoá
});

scene.onBeforeRenderObservable.add(() => {
  const dt = Math.min(engine.getDeltaTime() / 1000, 0.1);
  updateLocalPlayer(dt);
  updateStamina();
  updateAmmo();
  updateBigPunch();
  updateBigPunchHud();
  updateAttack();
  updatePickupHint();
  for (const r of remotes.values()) updateRemote(r, dt);
  updateSprintEffects(dt);
  for (const pickup of pickups.values()) updatePickup(pickup, dt);
  updateMatchHud();
  updateEventHud();
  updateDuelHud();
  updateBetFrame();
  updateTableGame();
  updateTableInvites();
  updatePlayerList();
  updateRingGates(dt);
  updateRingZone(dt);
  updateDuelTeams();
  updateAudienceEffects();
  updateThrowPreview();
  updateTomatoSplat();
  updateDogTracker();
  updatePoop();
  updatePoopHud();
  updateStinkOverlay();
  updatePoops(dt);
  updateLobbyHud();
  updateWater(dt);
  updateRockets(dt);
  updateGrenades(dt);
  updateWeather(dt);
  updateLightning(dt);
  updateStunEffects(dt);
  updateStunHud();
  updateIce();
  updateNuke(dt);
  updateCloud(dt);
  Fx.update(dt);
});

engine.runRenderLoop(() => scene.render());
addEventListener('resize', () => engine.resize());
